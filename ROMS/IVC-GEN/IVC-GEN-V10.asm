; LAYOUT (G812 hardware manual 3.2, software manual section 2 and ESC C/c)
;   * 128 characters x 16 bytes = 2048 bytes = the lower character generator
;     (IC20).  It serves character codes 00h-7Fh; codes 80h-FFh are served
;     by the upper generator (IC24, normally a RAM, the "PCG").
;   * The IVC Z80 sees the two generators as a 4K block at 4000h-5FFFh:
;       4000h-47FFh  this ROM   (char c, row r  ->  4000h + c*16 + r)
;       4800h-4FFFh  PCG RAM
;   * The CRTC supplies the row number on the low 4 address lines (RA0-RA3),
;     the VDU RAM supplies the character code on the next 8 (A4-A11).
;   * Each byte is one raster row of a character.  Bit 7 is the LEFT-most
;     dot (74LS165 shifts MSB first), bit 0 the right-most.  1 = dot on.
;   * Rows 0-15 are stored, but the standard screen uses 10 rows (0-9).  In
;     this ROM the glyphs use rows 1-7 (capitals, digits), with descenders on
;     rows 8-9; row 0 and rows 10-15 are always zero.
;   * Only code 20h (space) is completely blank.  Codes 00h-1Fh and 7Eh/7Fh
;     hold graphic symbols instead of control-code glyphs (control codes are
;     interpreted by the IVC and never displayed).
;
; EDITING
;   Each glyph is 16 DEFB lines (rows 0..15).  Change the %bbbbbbbb literal;
;   the trailing comment is only a picture (# = dot) and is not used by the
;   assembler, so update it by hand if you want.  The file always assembles
;   to exactly 2048 bytes (a guard at the end fails the build if the glyphs
;   overflow; keep every glyph at exactly 16 DEFB rows).
;
;   Build:   z80asm -o IVC-GEN-V10.bin IVC-GEN-V10.asm
;   Verify:  cmp IVC-GEN-V10.bin Originals/IVC-GEN-V10.BIN
;   Burn the .bin into IC20 (2716), or send individual glyphs to the PCG at
;   run time with ESC C (see IVC-PCG-DEMO.asm).
